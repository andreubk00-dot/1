def draw(rows):
    h = len(rows)
    w = max(len(r) for r in rows)
    im = Image.new("RGBA", (w, h), (0, 0, 0, 0))
    px = im.load()
    for y, row in enumerate(rows):
        for x, ch in enumerate(row):
            c = PAL.get(ch)
            if c is not None:
                px[x, y] = c + (255,)
    return im


def main(project):
    order = list(ICONS12.items()) + list(BASE24.items())
    cols_small = 16
    atlas = Image.new("RGBA", (16 * 14, 14 * 2 + 2 + 26), (0, 0, 0, 0))
    regions = {}
    x = y = 0
    for i, (name, rows) in enumerate(ICONS12.items()):
        im = draw(rows)
        cx, cy = (i % cols_small) * 14, (i // cols_small) * 14
        atlas.paste(im, (cx, cy), im)
        regions[name] = (cx, cy, im.width, im.height)
    base_y = 14 * 2 + 2
    for i, (name, rows) in enumerate(BASE24.items()):
        im = draw(rows)
        cx, cy = (i % 8) * 26, base_y
        atlas.paste(im, (cx, cy), im)
        regions[name] = (cx, cy, im.width, im.height)
    atlas.save(os.path.join(project, "ui_icons_v1.png"))
    print("const UI_ICON_REGIONS = {")
    print(",\n".join('    "%s":Rect2i(%d,%d,%d,%d)' % ((k,) + v) for k, v in regions.items()))
    print("}")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else ".")
